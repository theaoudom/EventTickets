CREATE TABLE TB_USER (
    USR_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USR_NM   VARCHAR(50)  NOT NULL UNIQUE,
    PWD      VARCHAR(100) NOT NULL,
    ROLE_CD  VARCHAR(10)  NOT NULL,
    REG_DTM  VARCHAR(14)  NOT NULL,
    MOD_DTM  VARCHAR(14)  NOT NULL,
    REG_ID   VARCHAR(50)  NOT NULL,
    MOD_ID   VARCHAR(50)  NOT NULL
);

CREATE TABLE TB_EVENT (
    EVT_ID    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVT_NM    VARCHAR(100)   NOT NULL,
    EVT_DTM   VARCHAR(14)    NOT NULL,
    VENUE_NM  VARCHAR(100)   NOT NULL,
    PRICE     NUMERIC(12, 2) NOT NULL CHECK (PRICE >= 0),
    TOT_SEAT  INT            NOT NULL CHECK (TOT_SEAT > 0),
    AVL_SEAT  INT            NOT NULL CHECK (AVL_SEAT >= 0),
    STS_CD    VARCHAR(10)    NOT NULL,
    REG_DTM   VARCHAR(14)    NOT NULL,
    MOD_DTM   VARCHAR(14)    NOT NULL,
    REG_ID    VARCHAR(50)    NOT NULL,
    MOD_ID    VARCHAR(50)    NOT NULL,
    CONSTRAINT CK_EVT_SEAT CHECK (AVL_SEAT <= TOT_SEAT)
);

CREATE TABLE TB_BOOKING (
    BKG_ID   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVT_ID   BIGINT         NOT NULL REFERENCES TB_EVENT (EVT_ID),
    USR_ID   BIGINT         NOT NULL REFERENCES TB_USER (USR_ID),
    QTY      INT            NOT NULL CHECK (QTY BETWEEN 1 AND 4),
    UNIT_PRC NUMERIC(12, 2) NOT NULL,
    TOT_AMT  NUMERIC(12, 2) NOT NULL,
    STS_CD   VARCHAR(10)    NOT NULL,
    REG_DTM  VARCHAR(14)    NOT NULL,
    MOD_DTM  VARCHAR(14)    NOT NULL,
    REG_ID   VARCHAR(50)    NOT NULL,
    MOD_ID   VARCHAR(50)    NOT NULL
);

CREATE INDEX IX_BKG_USR ON TB_BOOKING (USR_ID);
CREATE INDEX IX_BKG_EVT ON TB_BOOKING (EVT_ID);
